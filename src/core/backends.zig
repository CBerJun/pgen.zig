// pub const Resolver = struct {
//     fn resolveShiftReduce(self: *@This(), terminal: u32, nonterminal: u32) ?enum{shift, reduce} {}
//     fn resolveReduceReduce(self: *@This(), nonterminals: [2]u32) ?u1 {}
