"""
This script generates `src/meta_cfg.zig`. Outputs to stdout.
Manual translation from meta-grammar (at tools/meta_grammar.txt) to `Cfg`
for bootstrapping.
"""

from enum import IntEnum
from types import SimpleNamespace
from typing import TypeAlias
from dataclasses import dataclass

class Nt(IntEnum):
    # FYI, IntEnum.__format__ is int.__format__
    grammar = 0
    token_decl = 1
    production = 2
    rhs_atom = 3
    rhs_term = 4
    rhs_factor = 5
    rhs = 6
    nonterminal_qualifier = 7

print('//! Do not edit - auto generated by tools/generate_meta_cfg.py')
print('//! Meta-grammar for bootstrapping')
print('const cfg = @import("./cfg.zig");')

fields: list[str] = []

symbols = [
    ";",
    "[",
    "]",
    "{",
    "}",
    "(",
    ")",
    "*",
    ":",
    "|",
    "+",
]
keywords = [
    "epsilon",
    "tokens",
    "entry",
    "nodeless",
]

total_literal_tokens = len(symbols) + len(keywords)

@dataclass
class Terminal:
    tid: int

def sym(s: str) -> Terminal:
    return Terminal(symbols.index(s))
def kw(s: str) -> Terminal:
    return Terminal(keywords.index(s) + len(symbols))

terminals_fields: list[str] = []

terminals_fields.append(
    '.literal = &[_]cfg.LiteralCollection{'
    '.{.suffix = "", .literals = &[_][]const u8{%s}},'
    '.{.suffix = "k", .literals = &[_][]const u8{%s}},'
    '}'
    % tuple(
        ','.join(f'"{s}"' for s in ls)
        for ls in (symbols, keywords)
    )
)

named_tokens = [
    "STRING",
    "WORD",
]

NamedToken = SimpleNamespace()
for tid, name in enumerate(named_tokens, start=total_literal_tokens):
    setattr(NamedToken, name, Terminal(tid))

terminals_fields.append(
    '.named = &[_][]const u8{%s}'
    % ','.join(f'"{s}"' for s in named_tokens)
)
total_regular_terminals = total_literal_tokens + len(named_tokens)
# Don't forget the End of Input terminal
terminals_fields.append(f'.count = {total_regular_terminals + 1}')
terminals_fields.append(f'.eoi = {total_regular_terminals}')

fields.append('.terminals = .{%s}' % ','.join(terminals_fields))

nonterminals_fields: list[str] = []

nonterminals_fields.append(f'.entry = {Nt.grammar}')

nonterminals_fields.append('.names = &[_][]const u8{%s}' % ','.join(
    f'"{nt.name}"' for nt in Nt
))
# No node is nodeless:
nonterminals_fields.append(f'.node_forming_count = {len(Nt)}')

total_aux_nt = 0
Symbol: TypeAlias = Terminal | Nt | int  # int is a temporary nt
productions: list[None | list[list[Symbol]]] = [None] * len(Nt)

def new_aux_nt() -> int:
    """New auxiliary nonterminal."""
    global total_aux_nt
    total_aux_nt += 1
    productions.append(None)
    return len(Nt) + total_aux_nt - 1

token_decl_list = new_aux_nt()
production_list = new_aux_nt()
productions[Nt.grammar] = [[
    kw('tokens'), sym('{'), token_decl_list, sym('}'),
    kw('entry'), NamedToken.WORD, sym(';'),
    production_list,
]]
productions[token_decl_list] = [
    [Nt.token_decl],
    [token_decl_list, Nt.token_decl],
]
productions[production_list] = [
    [Nt.production],
    [production_list, Nt.production],
]
productions[Nt.token_decl] = [
    [NamedToken.WORD, sym(';')],
    [NamedToken.STRING, sym(';')],
]
productions[Nt.production] = [[
    Nt.nonterminal_qualifier, NamedToken.WORD, sym(':'), Nt.rhs, sym(';')
]]
productions[Nt.nonterminal_qualifier] = [
    [],
    [kw('nodeless')],
]

productions[Nt.rhs_atom] = [
    [NamedToken.WORD],
    [NamedToken.STRING],
    [sym('('), Nt.rhs, sym(')')],
    [sym('['), Nt.rhs, sym(']')],
]
productions[Nt.rhs_term] = [
    [Nt.rhs_atom],
    [Nt.rhs_atom, sym('*')],
    [Nt.rhs_atom, sym('+')],
]
rhs_term_list = new_aux_nt()
productions[rhs_term_list] = [
    [Nt.rhs_term],
    [rhs_term_list, Nt.rhs_term],
]
productions[Nt.rhs_factor] = [
    [rhs_term_list],
    [kw('epsilon')],
]
alternatives = new_aux_nt()
productions[alternatives] = [
    [],
    [alternatives, sym('|'), Nt.rhs_factor],
]
productions[Nt.rhs] = [[
    Nt.rhs_factor,
    alternatives,
]]

nonterminals_fields.append(f'.count = {len(Nt) + total_aux_nt}')

fields.append('.nonterminals = .{%s}' % ','.join(nonterminals_fields))

def _convert_symbol(symbol: Symbol) -> str:
    """Return Zig `cfg.Symbol` object string matching `Symbol`."""
    if isinstance(symbol, int):  # This includes `Nt`
        return '.{.nonterminal = %d}' % symbol
    if isinstance(symbol, Terminal):
        return '.{.terminal = %d}' % symbol.tid

flat_production_rhs: list[str] = []
flat_production_lhs: list[int] = []
production_pact: list[int] = []

pact = 0
for lhs, all_rhs in enumerate(productions):
    assert all_rhs is not None
    production_pact.append(pact)
    for rhs in all_rhs:
        flat_production_rhs.append(
            '&[_]cfg.Symbol{%s}' % ','.join(map(_convert_symbol, rhs)))
        flat_production_lhs.append(lhs)
    pact += len(all_rhs)

fields.append(f'.total_productions = {pact}')
fields.append('.productions = &[_][]const cfg.Symbol{%s}' % ','.join(flat_production_rhs))
fields.append('.production_pact = &[_]u32{%s}' % ','.join(map(str, production_pact)))
fields.append('.production_lhs = &[_]u32{%s}'
              % ','.join(map(str, flat_production_lhs)))

print('pub const meta_cfg: cfg.Cfg = .{%s};' % ','.join(fields))
